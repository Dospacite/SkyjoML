"""Render docs/results.md from the JSON reports in artifacts/reports (numbers are never typed by hand)."""

import glob
import json
from pathlib import Path

R = Path("artifacts/reports")


def load(name):
    p = R / name
    return json.load(open(p)) if p.exists() else None


def pct(x):
    return f"{100 * x:.1f}%"


lines = ["# Results", "", "Generated by `benchmarks/make_report.py` from `artifacts/reports/*.json`.", ""]
lines += [
    "Unit conventions: **win credit** is the candidate's expected share of the win (1/k for a k-way tie).",
    "**credit × n** rescales it by the table size so that 1.0 is parity at any player count "
    "(e.g. 2.0 at 4 players = 50% win credit where a random seat gets 25%).",
    "Every cell uses paired deals: each deal seed is played n times with the candidate rotated through every seat;",
    "95% intervals are percentile bootstraps over deal blocks (seed + all rotations).",
    "",
]

prim = load("release_primary_4p.json")
if prim:
    m = prim["metrics"]
    w, c = m["win_credit"], m["credit_x_n"]
    lines += [
        "## Primary release result (sealed seeds)",
        "",
        f"4 players, candidate vs 3 × `finish_tuned`, {m['credit_x_n']['n_matches']:,} matches "
        f"({m['credit_x_n']['n_blocks']:,} deals × 4 seatings), release seed range, policy-only (arg-max):",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Win credit | **{pct(w['mean'])}** (95% CI {pct(w['ci_lo'])} – {pct(w['ci_hi'])}); parity 25% |",
        f"| Credit × n | {c['mean']:.3f} ({c['ci_lo']:.3f} – {c['ci_hi']:.3f}) |",
        f"| Strict / shared win rate | {pct(m['strict_win_rate'])} / {pct(m['shared_win_rate'])} |",
        f"| Mean finishing rank (1 = best) | {m['mean_rank']:.2f} |",
        f"| Final total minus best opponent | {m['score_minus_best_opp']:+.1f} points |",
        f"| Mean round score | {m['mean_round_score']:.1f} |",
        f"| Finisher penalties per round | {m['finisher_penalty_per_round']:.3f} |",
        f"| Rounds / decisions per match | {m['rounds_per_match']:.2f} / {m['decisions_per_match']:.0f} |",
        f"| Truncated matches | {m['truncated']} |",
        "",
    ]

rel = load("release_benchmark.json")
if rel:
    det = rel["details"]
    opps = ["random", "greedy", "column", "finish", "finish_tuned", "mixed"]
    players = sorted({int(k.split("p")[0]) for k in det})
    lines += [
        "## Release table: all player counts (sealed seeds, policy-only)",
        "",
        f"{rel['n_seeds']} deals per cell × n seat rotations. Cells show credit × n with 95% CI; "
        "`mixed` = candidate vs a rotating mix of greedy/column/finish/finish_tuned seats.",
        "",
        "| Players | " + " | ".join(opps) + " |",
        "| --- | " + " | ".join(["---"] * len(opps)) + " |",
    ]
    for n in players:
        row = []
        for o in opps:
            k = f"{n}p vs {o}" if o != "mixed" else f"{n}p mixed"
            if k not in det:
                row.append("–")
                continue
            c = det[k]["credit_x_n"]
            t = det[k]["truncated"]
            row.append(f"{c['mean']:.2f} ({c['ci_lo']:.2f}–{c['ci_hi']:.2f})" + (f" †{t}" if t else ""))
        lines.append(f"| {n} | " + " | ".join(row) + " |")
    lines += ["", "† = number of matches stopped by the watchdog (all-heuristic stretches of a table can fail to end a round); "
              "they are included with zero credit for the candidate, so those cells are slightly conservative.",
              "", "Win-credit percentages vs `finish_tuned` (parity = 1/n):", "",
              "| Players | Parity | Candidate | Strict wins | Mean rank | Round score | Truncated |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for n in players:
        d = det.get(f"{n}p vs finish_tuned")
        if d:
            lines.append(f"| {n} | {pct(1 / n)} | {pct(d['win_credit']['mean'])} | {pct(d['strict_win_rate'])} | "
                         f"{d['mean_rank']:.2f} | {d['mean_round_score']:.1f} | {d['truncated']} |")
    mir = {k: v for k, v in rel["summary"].items() if "mirror" in k}
    if mir:
        lines += ["", "Mirror self-play seat check (candidate in every seat; credit × n per seat, parity 1.0; "
                  "seat 0 opens the first commit round only):", ""]
        for k, v in mir.items():
            lines.append(f"- {k.split(' ')[0]}: {', '.join(f'{x:.2f}' for x in v)}")
    lines.append("")

sc = load("seed_compare.json")
if sc:
    lines += ["## Training seeds (development seeds, policy-only)", "",
              "Three independent PPO seeds, 6M decisions each after the shared behaviour-cloning warm start; 300 deals × n "
              "rotations per cell.", "", "| Cell | Checkpoint | credit × n (95% CI) |", "| --- | --- | --- |"]
    for k, v in sc.items():
        cell, ck = k.split(" | ")
        c = v["credit_x_n"]
        lines.append(f"| {cell} | `{ck}` | {c['mean']:.3f} ({c['ci_lo']:.3f}–{c['ci_hi']:.3f}) |")
    lines.append("")

p4, po = load("promote_4p.json"), load("promote_other.json")
if p4:
    lines += ["## Promotion test (development seeds)", "",
              f"Candidate `{p4['candidate']}` (seed 3 continued to 14M decisions with the other seeds' final policies in "
              f"its league) vs incumbent `{p4['incumbent']}`, paired on identical deals/seatings vs `finish_tuned`. "
              "Material regression threshold: 2 percentage points of win credit (0.02 × n in credit × n).", "",
              "| Cell | Candidate | Incumbent | Paired diff (95% CI) |", "| --- | --- | --- | --- |"]
    for src in (p4, po):
        if src:
            for k, v in src["results"].items():
                lines.append(f"| {k} | {v['a']:.3f} | {v['b']:.3f} | {v['diff']:+.3f} ({v['ci95'][0]:+.3f} – {v['ci95'][1]:+.3f}) |")
    lines.append("")

srch = sorted(glob.glob(str(R / "search_*.json")))
if srch:
    lines += ["## Search vs policy-only (paired, development seeds)", "",
              "Same deals, seats and opponents; search = belief-sampled root Monte Carlo, top-k prior pruning, sequential "
              "halving, neural rollouts to the stated horizon then value head. Decisions where the policy's top action has "
              "probability ≥ 0.95 (and setup) are not searched. Latency is per searched decision on one busy core of the "
              "reference machine.", "",
              "| Report | Checkpoint / opponent | Budget | Matches | Policy-only | Search | Paired gain (95% CI) | p50 / p95 latency | Changed |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for p in srch:
        d = json.load(open(p))
        sc_ = d["search_config"]
        hz = "round end" if sc_["horizon"] < 0 else f"{sc_['horizon']} decisions"
        g = d["paired_gain"]
        lines.append(
            f"| `{Path(p).stem}` | {d.get('checkpoint', '')} {d['opponent']} | {sc_['rollouts']} rollouts, top-{sc_['top_k']}, {hz} | "
            f"{d['matches']} | {d['policy_only']['mean']:.3f} | {d['search']['mean']:.3f} | "
            f"{g['mean']:+.3f} ({g['ci_lo']:+.3f} – {g['ci_hi']:+.3f}) | "
            f"{d['latency_s']['p50']:.2f}s / {d['latency_s']['p95']:.2f}s | {pct(d['changed_action_rate'])} |")
    lines.append("")

v = load("validate_100k.json")
eng = load("benchmark_engine.json")
if v or eng:
    lines += ["## Engine integrity and speed", ""]
if v:
    e = v["errors"]
    lines += [f"- Randomized gate: {v['matches']:,} complete matches ({v['decisions']:,} decisions; policy mix "
              f"{v['policy_mix']}), errors {e} → **{'PASS' if v['ok'] else 'FAIL'}**. "
              f"{v['truncated_or_capped']} matches hit the watchdog"
              + (f" (by policy: {v['truncated_by_policy']})" if "truncated_by_policy" in v else "") + "."]
    b = load("validate_10k_breakdown.json")
    if b:
        lines += [f"- Breakdown rerun ({b['matches']:,} matches, seed 7, errors {sum(b['errors'].values())}): watchdog stops by "
                  f"policy {b['truncated_by_policy']} out of {b['policy_mix']}. All come from all-heuristic tables, most likely because the "
                  "`finish` heuristic avoids revealing its last card when it expects to be doubled (not separately diagnosed), so a table of them "
                  "can cycle indefinitely. Truncated matches are never scored as results; training saw 4 in ~107k matches."]
if eng:
    lines += ["- Batch engine, single thread, uniform-random legal actions incl. observation/mask generation: "
              + ", ".join(f"{k}p {v_:,}/s" for k, v_ in eng["engine_transitions_per_s"].items()) + " transitions.",
              "- Heuristic ladder (credit × n, 200 dev deals × rotations): "
              + "; ".join(f"{k} {v_}" for k, v_ in eng["heuristic_baselines"].items()) + "."]
Path("docs/results.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
